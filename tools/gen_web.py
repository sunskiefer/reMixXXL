#!/usr/bin/env python3
"""web/index.html -> src/web_page.h (the companion page as a C string the plugin serves)."""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
html = open(os.path.join(root, "web", "index.html"), encoding="utf-8").read()
import base64
ring = os.path.join(root, "web", "ring.webp")          # the jog wheel picture (from art/ui/ring/ring_user_transparent.png)
html = html.replace("__RING__", "data:image/webp;base64," + base64.b64encode(open(ring, "rb").read()).decode())
out = ["/* generated by tools/gen_web.py from web/index.html: do not edit */", "static const char RX_WEB_PAGE[] ="]
for line in html.split("\n"):
    b = (line + "\n").encode("utf-8")
    s = "".join(chr(c) if 32 <= c < 127 and chr(c) not in '"\\?' else "\\%03o" % c for c in b)
    out.append('    "%s"' % s)
out.append(";")
new = "\n".join(out) + "\n"
p = os.path.join(root, "src", "web_page.h")
if not os.path.exists(p) or open(p).read() != new:
    open(p, "w").write(new)
print("gen_web: %d bytes of page" % len(html.encode("utf-8")))

# the map builder page (web/mapbuilder.html -> src/map_page.h)
mhtml = open(os.path.join(root, "web", "mapbuilder.html"), encoding="utf-8").read()
out = ["/* generated by tools/gen_web.py from web/mapbuilder.html: do not edit */", "static const char RX_MAP_PAGE[] ="]
for line in mhtml.split("\n"):
    b = (line + "\n").encode("utf-8")
    s = "".join(chr(c) if 32 <= c < 127 and chr(c) not in '"\\?' else "\\%03o" % c for c in b)
    out.append('    "%s"' % s)
out.append(";")
newm = "\n".join(out) + "\n"
pm = os.path.join(root, "src", "map_page.h")
if not os.path.exists(pm) or open(pm).read() != newm:
    open(pm, "w").write(newm)
print("gen_web: %d bytes of map builder page" % len(mhtml.encode("utf-8")))
